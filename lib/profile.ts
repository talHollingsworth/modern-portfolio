import base from "@/data/profile.json";
import caseStudies from "@/data/case-studies.json";
import linkedin from "@/data/linkedin.json";
import recommendations from "@/data/recommendations.json";

export type Link = { label: string; href: string };
export type Project = {
  title: string;
  role: string;
  description?: string;
  image?: string;
  alt?: string;
  images?: { src: string; alt: string }[];
  links: Link[];
};
export type Job = {
  title: string;
  company: string;
  start: string;
  end: string;
  bullets: string[];
};
export type School = { school: string; degree: string; start: string; end: string };
// A LinkedIn recommendation. `image` is optional: LinkedIn exports don't include
// portraits, so new recommenders get an initials avatar until one is added by hand.
export type Recommendation = {
  name: string;
  role: string;
  company: string;
  quote: string;
  image?: string;
};
export type CaseStudy = {
  title: string;
  role: string;
  challenge: string;
  approach: string;
  accessibility: string;
  outcome: string;
  technologies: string[];
};

// Shape of data/linkedin.json; every field is optional because the sync
// only writes what the LinkedIn export contained.
type LinkedInData = Partial<{
  headline: string;
  summary: string;
  skills: string[];
  experience: Job[];
  education: School[];
  syncedAt: string;
}>;

const li = linkedin as LinkedInData;

// Single object the page reads from. Three sources feed it:
//  - data/linkedin.json   -> headline, About text, skills, jobs, education
//                            (generated by `npm run sync:linkedin`, do not hand-edit
//                            except to override the summary)
//  - data/profile.json    -> portfolio-only content LinkedIn doesn't have
//                            (name, links, résumé, projects)
//  - data/recommendations.json -> recommendation carousel; `npm run sync:linkedin`
//                            appends new LinkedIn recommendations and keeps manual edits
//  - data/case-studies.json -> anonymized engineering case studies
export const profile = {
  ...base,
  title: li.headline ?? "",
  summary: li.summary ?? "",
  skills: li.skills ?? [],
  experience: (li.experience ?? []) as Job[],
  education: (li.education ?? []) as School[],
  projects: base.projects as Project[],
  caseStudies: caseStudies as CaseStudy[],
  recommendations: recommendations as Recommendation[],
  syncedAt: li.syncedAt,
};

// Prefixes public asset paths with the sub-path when hosted under one
// (BASE_PATH in next.config.ts); empty when served from the domain root.
export const asset = (path: string) =>
  `${process.env.NEXT_PUBLIC_BASE_PATH ?? ""}${path}`;
